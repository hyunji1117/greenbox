// 길이가 긴 이름부터 찾아야 "양배추"가 "배"로, "고구마"가 "구마"로 잘못 잡히지 않는다
const KEYS = Object.keys(FOOD_ICON).sort((a, b) => b.length - a.length);

export function foodIconFor(name: string): string | null {
  const plain = name.replace(/\s+/g, '');
  const key = KEYS.find(k => plain.includes(k));
  return key ? `/foods/${FOOD_ICON[key]}.png` : null;
}
