-- 잘못 넣은 식재료를 지우는 "잘못 넣었어요(삭제)"를 위해 앱 계정에 items 삭제 권한을 준다 (2026-11-22)
-- - 버림(finished, 먹은 양이 남음)은 상해서 버린 것이라 통계와 쓰레기통에 남는다. 잘못 넣은 것까지 버림으로 지우면 통계가 꼬였다
-- - 삭제는 행을 지운다. 댓글(item_comments)과 알림 설정(0009)은 ON DELETE CASCADE로 함께 지워진다
--   (외래 키의 연쇄 삭제는 테이블 소유자 권한으로 돌아 앱 계정에 그 표들의 DELETE 권한은 따로 주지 않는다)
-- - 같은 냉장고 구성원만 지울 수 있게 하는 것은 서버(app/lib/items/store.ts deleteItem)가 지킨다
-- 0004에서 "품목 삭제 화면이 없어서 DELETE는 주지 않는다"고 했던 것을 이 화면이 생겨 바꾼다
-- 권한만 더하는 변경이라 코드를 이전 커밋으로 되돌려도 그대로 동작한다 (예전 코드는 지우지 않는다)
-- 실행: 관리자 계정(vultradmin)으로 greenbox DB에 직접 연결해서 실행한다. (풀 X)
-- 코드를 배포하기 전에 실행한다 (먼저 배포하면 삭제 요청이 권한 오류로 실패한다)

